// Package main. render.go generates Markdown reports from grouped benchmark
// results. Handles ALL presentation concerns: headers, tables, deltas,
// and formatting. Contains NO parsing or aggregation logic.
package main

import (
	"bufio"
	"fmt"
	"os"
	"sort"
	"strings"
)

// ----------------------------------------- Public API ----------------------------------------- //

// WriteMarkdownReport generates the complete benchmarks.md file.
func WriteMarkdownReport(path string, groups map[string][]BenchResult, runs int, cfg Config) error {
	f, err := os.Create(path)
	if err != nil {
		return fmt.Errorf("create %s: %w", path, err)
	}
	defer f.Close()

	writer := bufio.NewWriter(f)
	defer writer.Flush()

	writeHeader(writer, runs, cfg)
	writeSections(writer, groups, cfg)

	return nil
}

// -------------------------------------- Internal Helpers -------------------------------------- //

// writeHeader outputs the document preamble.
func writeHeader(w *bufio.Writer, runs int, cfg Config) {
	fmt.Fprintln(w, "<!-- benchmarks.md is auto-generated by `just bench`. DO NOT EDIT. -->")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "# ⚡ Performance Benchmarks")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "Generated from `go test -bench=. -benchmem` via `just bench`.")
	if runs > 1 {
		fmt.Fprintf(w, "Values shown are the **median of %d runs** per benchmark.\n", runs)
	}
	fmt.Fprintln(w, "Lower `ns/op`, `B/op` and `allocs/op` are better.")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "Each table compares one workload across implementation styles; the")
	fmt.Fprintf(w, "**vs %s** column is the delta against the baseline style.\n", cfg.Styles[0])
	fmt.Fprintln(w, "Deltas under 2% are reported as *on par* (benchmark noise).")
	fmt.Fprintln(w)
}

// writeSections iterates through categories and writes each group's table.
func writeSections(w *bufio.Writer, groups map[string][]BenchResult, cfg Config) {
	titles := buildSectionTitles(cfg)

	for _, title := range titles {
		keys := collectKeysForCategory(title, groups, cfg)
		if len(keys) == 0 {
			continue
		}
		sort.Strings(keys)

		fmt.Fprintf(w, "## %s\n\n", title)
		for _, k := range keys {
			writeGroupTable(w, k, groups[k], cfg)
		}
	}
}

// buildSectionTitles returns ordered section titles without duplicates.
func buildSectionTitles(cfg Config) []string {
	titles := []string{cfg.BasicTitle}
	seen := map[string]bool{cfg.BasicTitle: true}

	for _, c := range cfg.Categories {
		if !seen[c.Title] {
			seen[c.Title] = true
			titles = append(titles, c.Title)
		}
	}
	return titles
}

// collectKeysForCategory finds all group keys belonging to a section.
func collectKeysForCategory(title string, groups map[string][]BenchResult, cfg Config) []string {
	var keys []string
	for k := range groups {
		if CategoryForKey(k, cfg) == title {
			keys = append(keys, k)
		}
	}
	return keys
}

// CategoryForKey determines which section a workload key belongs to.
func CategoryForKey(key string, cfg Config) string {
	for _, c := range cfg.Categories {
		if strings.Contains(key, c.Contains) {
			return c.Title
		}
	}
	return cfg.BasicTitle
}

// writeGroupTable renders a single workload group as a Markdown table.
func writeGroupTable(w *bufio.Writer, key string, rows []BenchResult, cfg Config) {
	baselineNs, hasBaseline, baselineCount := findBaseline(rows, cfg)

	if baselineCount > 1 {
		fmt.Fprintf(os.Stderr, "⚠️  group %q has %d baseline rows — check groupRules\n", key, baselineCount)
	}

	fmt.Fprintf(w, "### %s\n\n", FormatCamelCase(key))
	fmt.Fprintf(w, "| Benchmark | Iterations | ns/op | B/op | allocs/op | vs %s |\n", cfg.Styles[0])
	fmt.Fprintln(w, "|---|---:|---:|---:|---:|---|")

	for _, r := range rows {
		comparison := formatComparison(r, baselineNs, hasBaseline, cfg)
		fmt.Fprintf(w, "| `%s` | %s | %s | %s | %s | %s |\n",
			r.PrettyName,
			FormatThousands(r.Iterations),
			FormatNsOp(r.NsPerOp),
			FormatThousands(r.BytesPerOp),
			FormatThousands(r.AllocsPerOp),
			comparison,
		)
	}
	fmt.Fprintln(w)
}

// findBaseline locates the fastest baseline-style result in a group.
func findBaseline(rows []BenchResult, cfg Config) (ns float64, found bool, count int) {
	for _, r := range rows {
		if r.Style == cfg.Styles[0] {
			count++
			if !found || r.NsPerOp < ns {
				ns = r.NsPerOp
				found = true
			}
		}
	}
	return
}

// formatComparison renders the delta label against baseline.
func formatComparison(r BenchResult, baselineNs float64, hasBaseline bool, cfg Config) string {
	if r.Style == cfg.Styles[0] {
		return "baseline"
	}
	if !hasBaseline {
		return "—"
	}
	return CompareLabel(r.NsPerOp, baselineNs)
}
